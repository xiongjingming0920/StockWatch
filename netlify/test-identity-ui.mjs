// Contract tests for the login UI; these do not simulate Netlify Identity itself.
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';

let source=await readFile(new URL('../frontend/vendor/identity-ui.js',import.meta.url),'utf8');
source=source.replace(/^import .* from '\.\/identity-client\.js';/, `const {login, signup, logout: identityLogout, getUser, handleAuthCallback, acceptInvite, requestPasswordRecovery, updateUser} = globalThis.__identityMock;`);
assert.ok(!source.startsWith('import '),'SDK mock must replace the import');
let run=0;
async function scenario(status, body={}, overrides={}, options={}) {
 const elements=new Map();
 let reloads=0;
 globalThis.document={querySelector(selector){if(!elements.has(selector))elements.set(selector,{hidden:true,textContent:'',value:'',handlers:{},attributes:{},setAttribute(name,value){this.attributes[name]=value},addEventListener(event,fn){this.handlers[event]=fn}});return elements.get(selector)}};
 globalThis.window={location:{reload(){reloads++}}};
 globalThis.__identityMock={login:async()=>{},signup:async()=>{},logout:async()=>{},getUser:async()=>null,handleAuthCallback:async()=>null,acceptInvite:async()=>{},requestPasswordRecovery:async()=>{},updateUser:async()=>{},...overrides};
 globalThis.fetch=async()=>({ok:status===200,status,json:async()=>body});
 const mod=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64')+'#'+(++run));
 const user=await mod.requireLogin(options);
 for(const selector of ['#authPanel','#authMessage','#authTitle','#authTabs','#authRegister','#authRegisterClosed','#authSignup','#authSignupEmail','#authSignupPassword','#authSignupConfirm','#authSwitchAccount','#authShowLogin','#authShowRegister','#authLogin','#authSetPassword','#authIntro','#authEmail','#authPassword','#authNewPassword','#authForgot'])document.querySelector(selector);
 return {user,elements,getReloads:()=>reloads};
}
let x=await scenario(200,{auth_mode:'identity',user:{id:'user-1',email:'x@example.test'}});
assert.equal(x.user.id,'user-1','session endpoint user must be unwrapped');
x=await scenario(401);
assert.equal(x.user,null);assert.equal(x.elements.get('#authPanel').hidden,false,'unauthenticated user sees login panel');
assert.equal(x.elements.get('#authTabs').hidden,false);
x.elements.get('#authShowRegister').handlers.click();
assert.equal(x.elements.get('#authLogin').hidden,true);assert.equal(x.elements.get('#authRegister').hidden,false);
assert.match(x.elements.get('#authIntro').textContent,/暂不开放/);
assert.equal(x.elements.get('#authSignup').hidden,true);
await x.elements.get('#authSignup').handlers.submit({preventDefault(){}});
assert.equal(x.elements.get('#authMessage').textContent,'','closed registration must not submit');
x.elements.get('#authShowLogin').handlers.click();
assert.equal(x.elements.get('#authLogin').hidden,false);assert.equal(x.elements.get('#authRegister').hidden,true);
x=await scenario(503);
assert.equal(x.user,null);assert.equal(x.elements.get('#authLogin').hidden,true,'service error must not be mistaken for a login attempt');
let accepted, loggedIn;
x=await scenario(401,{}, {handleAuthCallback:async()=>({type:'invite',token:'test-token'}),acceptInvite:async(token,password)=>{accepted={token,password};return {email:'invited@example.test'}},login:async(email,password)=>{loggedIn={email,password}}});
assert.equal(x.elements.get('#authSetPassword').hidden,false);
assert.equal(x.elements.get('#authTabs').hidden,true,'activation must present password setup');
x.elements.get('#authNewPassword').value='test-password';
await x.elements.get('#authSetPassword').handlers.submit({preventDefault(){}});
assert.deepEqual(accepted,{token:'test-token',password:'test-password'});
assert.equal(x.getReloads(),0,'invite acceptance must not assume an authenticated cookie');
assert.equal(x.elements.get('#authSetPassword').hidden,true);
assert.equal(x.elements.get('#authLogin').hidden,false);
assert.equal(x.elements.get('#authTabs').hidden,false);
assert.equal(x.elements.get('#authPassword').value,'');
assert.equal(x.elements.get('#authNewPassword').value,'');
assert.equal(x.elements.get('#authEmail').value,'invited@example.test');
assert.match(x.elements.get('#authMessage').textContent,/请登录/);
x.elements.get('#authPassword').value='test-password';
await x.elements.get('#authLogin').handlers.submit({preventDefault(){}});
assert.deepEqual(loggedIn,{email:'invited@example.test',password:'test-password'});
assert.equal(x.getReloads(),1,'explicit login reloads to verify the server session');
let resetPassword;
x=await scenario(401,{}, {handleAuthCallback:async()=>({type:'recovery',user:{email:'x@example.test'}}),updateUser:async data=>{resetPassword=data.password}});
x.elements.get('#authNewPassword').value='new-test-password';
await x.elements.get('#authSetPassword').handlers.submit({preventDefault(){}});
assert.equal(resetPassword,'new-test-password');assert.equal(x.getReloads(),1,'recovery retains its existing flow');
let signedUp=null;
x=await scenario(401,{}, {signup:async(email,password)=>{signedUp={email,password}}},{registration_open:true});
x.elements.get('#authShowRegister').handlers.click();
assert.equal(x.elements.get('#authSignup').hidden,false);
x.elements.get('#authSignupEmail').value='new@example.test';x.elements.get('#authSignupPassword').value='test-password';x.elements.get('#authSignupConfirm').value='test-password';
await x.elements.get('#authSignup').handlers.submit({preventDefault(){}});
assert.deepEqual(signedUp,{email:'new@example.test',password:'test-password'});
assert.equal(x.elements.get('#authSignupPassword').value,'');assert.match(x.elements.get('#authMessage').textContent,/验证邮件/);
x=await scenario(403);
assert.equal(x.elements.get('#authSwitchAccount').hidden,false,'forbidden accounts may switch');
assert.match(x.elements.get('#authMessage').textContent,/超级管理员/);
console.log('Identity UI session contract checks passed');
