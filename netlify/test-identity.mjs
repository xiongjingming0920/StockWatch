import assert from 'node:assert/strict';
import {authorize} from './lib/auth.mjs';
import handler from './functions/api.mjs';

const origin='https://example.test';
const req=(method='GET',headers={})=>new Request(origin+'/api/v1/dataset',{method,headers});
const identity={STOCKWATCH_AUTH_MODE:'identity'};
let a=await authorize(req(),{env:identity,identityUser:async()=>null});
assert.equal(a.status,401,'anonymous requests must fail closed');
a=await authorize(req('POST'),{env:identity,identityUser:async()=>({id:'u1'})});
assert.equal(a.status,403,'missing origin must be refused for POST');
a=await authorize(req('POST',{origin:'https://attacker.test'}),{env:identity,identityUser:async()=>({id:'u1'})});
assert.equal(a.status,403,'cross-site POST must be refused');
assert.equal((await authorize(req(),{env:identity,identityUser:async()=>({id:'ordinary',roles:[]})})).status,403,'closed beta must block non-admin users');
assert.equal((await authorize(req(),{env:{...identity,STOCKWATCH_ACCESS_MODE:'registered'},identityUser:async()=>({id:'ordinary',roles:[]})})).status,200,'explicit registered mode permits ordinary users');
assert.equal((await authorize(req(),{env:{...identity,STOCKWATCH_ACCESS_MODE:'typo'},identityUser:async()=>({id:'u1',roles:['super_admin']})})).status,503,'invalid policy must fail closed');
const u1=await authorize(req('POST',{origin}),{env:identity,identityUser:async()=>({id:'u1',email:'one@example.test',roles:['super_admin']})});
const u2=await authorize(req('POST',{origin}),{env:identity,identityUser:async()=>({id:'u2',roles:['super_admin']})});
assert.equal(u1.status,200);assert.equal(u2.status,200);assert.notEqual(u1.scope,u2.scope);
assert.equal(u1.scope.length,64);assert.equal(u1.user.id,'u1');
assert.equal((await authorize(req(),{env:{STOCKWATCH_AUTH_MODE:'mistyped'}})).status,503);
const secret='0123456789abcdef0123456789abcdef';
assert.equal((await authorize(req(),{env:{STOCKWATCH_SITE_TOKEN:secret}})).status,401);
assert.equal((await authorize(req('GET',{'x-stockwatch-token':secret}),{env:{STOCKWATCH_SITE_TOKEN:secret}})).status,200);
process.env.STOCKWATCH_AUTH_MODE='identity';
delete process.env.STOCKWATCH_SIGNUP_ENABLED;
let healthResponse=await handler(new Request(origin+'/api/v1/health'));
assert.equal((await healthResponse.json()).registration_open,false,'registration is hidden by default');
process.env.STOCKWATCH_SIGNUP_ENABLED='true';
healthResponse=await handler(new Request(origin+'/api/v1/health'));
assert.equal((await healthResponse.json()).registration_open,true,'signup display can be independently enabled');
assert.equal((await handler(req())).status,401,'handler must require identity, without a Netlify identity context');
assert.equal((await handler(req('POST',{origin:'https://attacker.test'}))).status,403);
// Simulate the platform-injected trusted identity context, never request-controlled input.
globalThis.netlifyIdentityContext={user:{sub:'u1',email:'one@example.test',app_metadata:{roles:['super_admin']}}};
const api=(path,opts={})=>new Request(origin+'/api/v1'+path,opts);
const batchResponse=await handler(api('/batches',{method:'POST',headers:{origin,'content-type':'application/json'},body:JSON.stringify({as_of_date:'2024-07-01',k:1,method:'rule'})}));
assert.equal(batchResponse.status,200);
const batch=await batchResponse.json();
let caseResponse=await handler(api('/batches/'+encodeURIComponent(batch.batch_id)+'/cases'));
let first=(await caseResponse.json()).items[0];
const review=await handler(api('/cases/'+encodeURIComponent(first.id)+'/reviews',{method:'POST',headers:{origin,'content-type':'application/json'},body:JSON.stringify({action:'REVIEWED'})}));
assert.equal(review.status,200);
caseResponse=await handler(api('/batches/'+encodeURIComponent(batch.batch_id)+'/cases'));
assert.equal((await caseResponse.json()).items[0].status,'REVIEWED');
globalThis.netlifyIdentityContext={user:{sub:'u2',email:'two@example.test',app_metadata:{roles:['super_admin']}}};
caseResponse=await handler(api('/batches/'+encodeURIComponent(batch.batch_id)+'/cases'));
assert.equal((await caseResponse.json()).items[0].status,'PENDING','user two must not see user one status');
globalThis.netlifyIdentityContext={user:{sub:'ordinary',user_metadata:{roles:['super_admin']}}};
assert.equal((await handler(req())).status,403,'editable user metadata must not grant administrator access');
delete globalThis.netlifyIdentityContext;
delete process.env.STOCKWATCH_AUTH_MODE;
delete process.env.STOCKWATCH_SIGNUP_ENABLED;
console.log('Identity fail-closed, origin, namespace and legacy-token checks passed');
