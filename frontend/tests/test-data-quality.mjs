import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import vm from 'node:vm';

const html=await readFile(new URL('../index.html',import.meta.url),'utf8');
const script=html.match(/<script>\s*([\s\S]*?)<\/script>/)?.[1];
assert.ok(script,'inline application script');
new vm.Script(script);
assert.match(html,/id="qualityPanel" hidden/);
assert.match(script,/qualityPanel'\)\.hidden=data\.auth_mode!==['"]local['"]/);
assert.match(script,/error\.dataQuality=d\.data_quality/);
assert.match(script,/showQuality\(err\.dataQuality\)/);
assert.match(script,/showQuality\(d\.data_quality\)/);

const section=script.slice(script.indexOf('// Data quality is available'),script.indexOf('const percent=v=>'));
assert.ok(section.includes('function qualityText'));
const elements=new Map();
for(const key of ['#date','#qualityCheck','#qualityResult'])elements.set(key,{hidden:true,disabled:false,value:key==='#date'?'2024-07-01':'',textContent:'',handlers:{},addEventListener(name,fn){this.handlers[name]=fn}});
let calls=[],response={status:'pass',as_of:'2024-07-01',row_count:12,errors:{},warnings:{}};
const context={document:{},$:(s)=>elements.get(s),toast:()=>{},req:async(path)=>{calls.push(path);return response}};
vm.createContext(context);
vm.runInContext(section+'\nglobalThis.renderQualityText=qualityText;globalThis.renderQuality=showQuality;',context);
await elements.get('#qualityCheck').handlers.click();
assert.equal(calls[0],'/data-quality?as_of=2024-07-01');
assert.match(elements.get('#qualityResult').textContent,/通过/);
assert.match(elements.get('#qualityResult').textContent,/不证明/);
context.renderQuality({status:'warn',errors:{},warnings:{missing_stock_hours:3}});
assert.match(elements.get('#qualityResult').textContent,/警告/);
assert.match(elements.get('#qualityResult').textContent,/缺货小时数缺失：3/);
context.renderQuality({status:'fail',errors:{missing_required_columns:1},checks:{missing_required_columns:['<img src=x>']}});
assert.match(elements.get('#qualityResult').textContent,/不能生成/);
assert.match(elements.get('#qualityResult').textContent,/<img src=x>/);
assert.equal(elements.get('#qualityResult').innerHTML,undefined,'untrusted content rendered as text');
elements.get('#date').handlers.change();
assert.equal(elements.get('#qualityResult').hidden,true);
elements.get('#date').value='';
response={status:'fail',errors:{file_not_found:1},warnings:{}};
await elements.get('#qualityCheck').handlers.click();
assert.equal(calls.at(-1),'/data-quality','checks work without available dates');
assert.match(elements.get('#qualityResult').textContent,/数据文件不存在/);
console.log('data quality frontend checks passed');
